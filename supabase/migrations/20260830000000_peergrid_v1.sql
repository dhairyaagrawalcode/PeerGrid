create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username extensions.citext unique,
  full_name text,
  avatar_url text,
  campus_id uuid references public.campuses(id) on delete restrict,
  graduation_year smallint check (graduation_year between 2024 and 2040),
  program text,
  bio text check (char_length(bio) <= 500),
  goals text check (char_length(goals) <= 500),
  github_url text,
  linkedin_url text,
  portfolio_url text,
  is_verified boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint username_format check (
    username is null or username::text ~ '^[a-z0-9][a-z0-9_-]{2,29}$'
  )
);

