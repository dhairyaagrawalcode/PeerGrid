create or replace function public.domain_is_allowed(candidate_email text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.allowed_email_domains d
    where d.is_active
      and lower(d.domain::text) = lower(split_part(candidate_email, '@', 2))
  );
$$;

create or replace function public.is_email_domain_allowed(candidate_email text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.domain_is_allowed(candidate_email);
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, is_verified)
  values (
    new.id,
    nullif(trim(coalesce(new.raw_user_meta_data ->> 'full_name', '')), ''),
    new.email_confirmed_at is not null and public.domain_is_allowed(new.email)
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function public.sync_verified_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.email_confirmed_at is not null then
    update public.profiles
    set is_verified = public.domain_is_allowed(new.email)
    where id = new.id;
  end if;
  return new;
end;
$$;

create trigger on_auth_user_verified
after update of email_confirmed_at, email on auth.users
for each row execute function public.sync_verified_profile();

create or replace function public.refresh_profile_verification()
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  verified boolean;
begin
  select u.email_confirmed_at is not null and public.domain_is_allowed(u.email)
  into verified
  from auth.users u
  where u.id = auth.uid();

  update public.profiles set is_verified = coalesce(verified, false)
  where id = auth.uid();

  return coalesce(verified, false);
end;
$$;

create or replace function public.is_verified_student(candidate_id uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = candidate_id and p.is_verified
  );
$$;

create or replace function public.hook_restrict_signup_by_email_domain(event jsonb)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  candidate_email text := event -> 'user' ->> 'email';
begin
  if candidate_email is not null and public.domain_is_allowed(candidate_email) then
    return '{}'::jsonb;
  end if;

  return jsonb_build_object(
    'error', jsonb_build_object(
      'http_code', 403,
      'message', 'Use an approved NST student email address to join PeerGrid.'
    )
  );
end;
$$;

